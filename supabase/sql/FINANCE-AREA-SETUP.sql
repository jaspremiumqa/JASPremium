-- Seed mappings from the existing Excel-imported financial_statements table.
insert into public.financial_statement_mappings(statement,account_code,section_line,display_order,active)
select f.statement,f.account_code,coalesce(nullif(f.classification_line,''),f.account_name),row_number() over(partition by f.statement order by f.account_code),coalesce(f.active,true)
from public.financial_statements f
where f.account_code is not null and exists(select 1 from public.chart_of_accounts c where c.account_code=f.account_code)
on conflict(statement,account_code) do update
set section_line=excluded.section_line, display_order=excluded.display_order, active=excluded.active;

