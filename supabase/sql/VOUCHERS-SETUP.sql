on public.vouchers
for delete
to authenticated
using ((select public.is_admin()));

-- ============================================================
-- Public Supabase Storage bucket for voucher images
-- ============================================================
insert into storage.buckets (id, name, public)
values ('vouchers', 'vouchers', true)
on conflict (id) do update set public = true;

drop policy if exists "crm_admin_upload_voucher_images" on storage.objects;
create policy "crm_admin_upload_voucher_images"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'vouchers'
  and (select public.is_admin())
);

drop policy if exists "crm_admin_update_voucher_images" on storage.objects;
create policy "crm_admin_update_voucher_images"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'vouchers'
  and (select public.is_admin())
)
with check (
  bucket_id = 'vouchers'
  and (select public.is_admin())
);

drop policy if exists "crm_admin_delete_voucher_images" on storage.objects;
create policy "crm_admin_delete_voucher_images"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'vouchers'
  and (select public.is_admin())
);

